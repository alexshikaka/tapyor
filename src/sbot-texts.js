function fmtTime(sec) {
  if (sec == null || !isFinite(sec)) return 'скоро';
  const m = Math.max(1, Math.round(sec / 60));
  return m + ' мин';
}

// Twitch не принимает сообщение длиннее 500 символов. Держим запас — 480, многоточие в конце.
const REPLY_MAX = 480;
function clip(s, n) {
  const t = String(s == null ? '' : s);
  const num = Number(n);
  const max = isFinite(num) && num > 0 ? Math.trunc(num) : REPLY_MAX;
  return t.length > max ? t.slice(0, max - 1) + '…' : t;
}

function render(template, vars) {
  const v = vars || {};
  return String(template).replace(/\{([^{}]+)\}/g, (all, key) => (v[key] != null ? String(v[key]) : all));
}

// «@ник» для подстановки {ник} или пустая строка. uid сюда не попадает никогда:
// шаблон может не прислать user, и тогда фраза должна быть без «@».
function nick(user) {
  const u = String(user == null ? '' : user).trim().replace(/^@+/, '');
  return u ? '@' + u : '';
}

// Убирает след пустого ника: запятую/тире в начале, двойные пробелы и (если cap) строчную
// первую букву. Так «{ник}, твой трек уже играет» при пустом нике становится «Твой трек уже играет»,
// а собственные фразы без ника (например, «слишком много заказов») остаются как написаны.
function tidy(s, cap) {
  let t = String(s == null ? '' : s).replace(/\s+/g, ' ').trim();
  t = t.replace(/^[\s,;:—–-]+/, '').trim();
  if (cap && /^[а-яёa-z]/.test(t)) t = t.charAt(0).toUpperCase() + t.slice(1);
  return t;
}

// custom — будущие правки стримера (Э4): { ключ: { on, text } }. Как в боте пака.
function make(key, vars, custom) {
  const base = DEFAULTS[key];
  if (!base) throw new Error('нет ответа ' + key);
  const c = (custom && custom[key]) || {};
  const on = c.on != null ? c.on : true;
  if (!on) return '';
  const tpl = String(c.text != null && c.text !== '' ? c.text : base);
  const v = vars || {};
  const out = render(tpl, v);
  // Фраза начинается с ника, а ника нет (шаблон не прислал user) — убираем след и поднимаем букву.
  return v['ник'] === '' && tpl.trim().indexOf('{ник}') === 0 ? tidy(out, true) : out;
}

