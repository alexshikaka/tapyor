'use strict';
// STAB-R8: память попыток отправки отчётов об ошибках на время работы программы.
// Отметка «уже отправляли сегодня» (reportsSent) ставится только после успешного ответа,
// поэтому при 429 каждая следующая глубокая проверка шлёт те же отчёты снова.
// Здесь — не чаще одной попытки в 10 минут на один отпечаток, независимо от ответа сервера.

const ATTEMPT_MS = 10 * 60 * 1000;

// Можно ли пытаться отправить отчёт с этим отпечатком сейчас. Чистая: состояние не меняет,
// отметку ставит вызывающий (main.js) перед самой попыткой.
function attemptAllowed(now, fp, state) {
  if (!fp) return true;
  const at = state && state[fp];
  return !(at && now - at < ATTEMPT_MS);
}

module.exports = { ATTEMPT_MS, attemptAllowed };
