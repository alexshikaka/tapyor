// G-06: свои ошибки облачных функций Тапёра — отдельным полем tapyor_error.
//
// Зачем: ответ функции и ответ внешнего сервиса (Яндекса, Google, DonationAlerts) выглядели одинаково,
// и Тапёр не мог отличить «облако перегружено, попробуй через минуту» от «провайдер отказал во входе».
// Теперь свои ошибки несут поле tapyor_error с кодом из списка ниже, а поле error остаётся прежним —
// старые сборки Тапёра (0.32 и раньше) читают только его и продолжают работать как раньше.
//
// Правило: tapyor_error есть только у НАШИХ ошибок. Ответ провайдера (например, invalid_grant от Google)
// уходит без tapyor_error — так сразу видно, что это отказ сервиса, а не сбой облака.
'use strict';

const CODES = {
  forbidden: 'нет или неверный общий ключ Тапёра',
  method: 'запрос не того метода (нужен POST)',
  rate_limited: 'лимит частоты: слишком много запросов с адреса или всего',
  daily_limit: 'суточный лимит новых автоотчётов исчерпан',
  not_configured: 'у функции не заданы переменные окружения (ключи сервиса)',
  too_big: 'тело запроса больше допустимого',
  bad_request: 'битый запрос: не JSON или нет обязательных полей',
  provider_timeout: 'внешний сервис не ответил вовремя',
  provider_unreachable: 'внешний сервис недоступен по сети',
  provider_bad_response: 'внешний сервис ответил не JSON',
  server: 'внутренняя ошибка функции'
};

// Свой ответ с ошибкой: error — как раньше (для старых сборок), tapyor_error — код для нового Тапёра.
// extra — дополнительные поля (например, retry_after).
function errBody(error, code, extra) {
  return Object.assign({ error, tapyor_error: code }, extra || {});
}

// Проверка: код должен быть из списка — иначе опечатка тихо превратится в «неизвестную ошибку»
function isKnown(code) { return Object.prototype.hasOwnProperty.call(CODES, code); }

// Текст для лога функции: наш код + прежняя строка, без значений запроса
function logLine(where, code, error) {
  return where + ': ' + code + (error ? ' (' + error + ')' : '');
}

module.exports = { CODES, errBody, isKnown, logLine };
