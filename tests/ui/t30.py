import os, asyncio, subprocess
from playwright.async_api import async_playwright
CH='/opt/pw-browsers/chromium-1194/chrome-linux/chrome'
srv = subprocess.Popen(['python3','-m','http.server','8786','--bind','127.0.0.1'], cwd='.', stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
def ok(c,m):
    print(('✓ ' if c else '✗ ')+m)
    if not c: raise SystemExit(1)
async def main():
    async with async_playwright() as p:
        b=await p.chromium.launch(executable_path=(CH if os.path.exists(CH) else None))
        pg=await b.new_page(viewport={'width':1280,'height':800}); await pg.add_init_script(path='mock5.js')
        errs=[]; pg.on('pageerror',lambda e:errs.append(str(e)))
        await pg.goto('http://127.0.0.1:8786/app2/index.html'); await pg.wait_for_timeout(800)
        await pg.click('[data-tab="wave"]'); await pg.wait_for_timeout(400)
        ok(await pg.evaluate("!document.getElementById('viewWave').hidden"), 'вкладка «Волна» открывается')
        ok(await pg.evaluate("!document.querySelector('.queue-col').hidden"), 'очередь остаётся справа')
        ok(await pg.evaluate("document.querySelectorAll('#wpDiv .wchip').length")==4, 'характер: 4 кнопки')
        ok(await pg.evaluate("document.querySelectorAll('#wpMood .wchip').length")==5, 'настроение: 5 кнопок')
        ok(await pg.evaluate("document.querySelectorAll('#wpLang .wchip').length")==4, 'язык: 4 кнопки')
        await pg.evaluate("document.querySelector('#wpDiv .wchip[data-v=favorite]').click()"); await pg.wait_for_timeout(200)
        ok(await pg.evaluate("waveCfg.diversity==='favorite'"), 'настройка меняет waveCfg')
        ok(await pg.evaluate("document.querySelector('#waveDiv .wchip[data-v=favorite]').classList.contains('active')"), 'панель в очереди синхронизирована')
        await pg.click('[data-tab="search"]'); await pg.wait_for_timeout(150); await pg.click('[data-tab="wave"]'); await pg.wait_for_timeout(250)
        ok(await pg.evaluate("!document.getElementById('viewWave').hidden"), 'возврат на вкладку работает')
        # «Что играет» в панели волны: тот же список, что «Для вас», без дубля «Моей волны»
        await pg.evaluate("document.getElementById('waveGear').click()"); await pg.wait_for_timeout(300)
        left = await pg.evaluate("Array.from(document.querySelectorAll('#wpCtx .wave-ctx-chip:not(.wave-my)')).map(x=>x.dataset.tip||x.title)")
        right = await pg.evaluate("Array.from(document.querySelectorAll('#waveVariants .wv')).map(x=>x.textContent.trim())")
        ok(right and right[0] == 'Моя волна — как обычно', '«Что играет»: первая строка — «Моя волна — как обычно»')
        ok(right.count('Моя волна') == 0, '«Что играет»: нет второй «Моей волны»')
        ok(right[1:] == left, '«Что играет» совпадает с «Для вас»: ' + str(right[1:]) + ' / ' + str(left))
        await pg.evaluate("Array.from(document.querySelectorAll('#wpCtx .wave-ctx-chip')).find(x=>(x.dataset.tip||x.title)==='Работаю').click()")
        await pg.wait_for_timeout(250)
        on = await pg.evaluate("Array.from(document.querySelectorAll('#waveVariants .wv.on')).map(x=>x.textContent.trim())")
        ok(on == ['Работаю'], 'выбор слева подсвечивает справа ровно одну строку: ' + str(on))
        left_on = await pg.evaluate("Array.from(document.querySelectorAll('#wpCtx .wave-ctx-chip.active')).map(x=>x.dataset.tip||x.title)")
        ok(left_on == ['Работаю'], 'выбор слева подсвечен и слева: ' + str(left_on))
        await pg.evaluate("Array.from(document.querySelectorAll('#waveVariants .wv')).find(x=>x.textContent.trim()==='В дороге').click()")
        await pg.wait_for_timeout(250)
        right_on = await pg.evaluate("Array.from(document.querySelectorAll('#waveVariants .wv.on')).map(x=>x.textContent.trim())")
        left_on = await pg.evaluate("Array.from(document.querySelectorAll('#wpCtx .wave-ctx-chip.active')).map(x=>x.dataset.tip||x.title)")
        ok(right_on == ['В дороге'] and left_on == ['В дороге'], 'выбор справа подсвечивает одно и то же: ' + str(right_on) + ' / ' + str(left_on))
        await pg.evaluate("ymLoggedIn=false; renderVariants()")
        ok(await pg.evaluate("document.getElementById('waveVariants').textContent.trim()") == 'Нужен вход в Яндекс', 'без входа — «Нужен вход в Яндекс»')
        await pg.evaluate("ymLoggedIn=true; renderVariants()")
        saved_ctx = await pg.evaluate("wpCtxData")
        await pg.evaluate("wpCtxData=[]; renderVariants()")
        rows = await pg.evaluate("Array.from(document.querySelectorAll('#waveVariants .wv')).map(x=>x.textContent.trim())")
        ok(rows == ['Моя волна — как обычно'], 'Яндекс не ответил — только «Моя волна — как обычно»')
        await pg.evaluate("v=>{wpCtxData=v; renderVariants()}", saved_ctx)
        await pg.evaluate("if(!document.getElementById('waveSettings').hidden) document.getElementById('waveGear').click()")
        await pg.wait_for_timeout(150)
        for skin in ('dos', 'crt', 'retro', ''):
            await pg.click('[data-tab="look"]'); await pg.wait_for_timeout(200)
            await pg.evaluate("s=>document.querySelector('#viewLook [data-skin=\"'+s+'\"]').click()", skin); await pg.wait_for_timeout(250)
            await pg.click('[data-tab="wave"]'); await pg.wait_for_timeout(300)
            cls = await pg.evaluate("document.documentElement.className")
            ok((skin in cls) if skin else ('skin-' not in cls), 'оболочка ' + (skin or 'стандарт') + ' применяется: ' + cls)
            await pg.set_viewport_size({'width':900,'height':600}); await pg.wait_for_timeout(250)
            ok(await pg.evaluate("document.documentElement.scrollWidth<=innerWidth"), '900×600 без переполнения: ' + (skin or 'стандарт'))
        ok(not errs, 'без ошибок' + (': '+'; '.join(errs) if errs else ''))
        await b.close()
try: asyncio.run(main())
finally: srv.terminate()
